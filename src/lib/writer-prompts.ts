- 标题与正文分别怎样吸引注意，正文先给什么、暂缓什么，第一段怎样进入下一段；不要把标题当成正文开头。
- 信息如何推进：相邻句靠什么关系接上，解释、原话、动作、反应各自起什么作用。既观察显式转场，也观察没有连接词的直接承接。
- 语言节奏怎样形成：句子如何伸缩，哪里重复、停顿、改口，哪些词承担重音。口头禅与词频不是节奏本身。
