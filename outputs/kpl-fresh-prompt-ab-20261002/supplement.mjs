import path from 'node:path';
import nextEnv from '@next/env';
import { generateCommentBatch } from '../../src/lib/engagement.ts';
import { readJsonFile, writeJsonFile, writeTextFileAtomic } from '../../src/lib/storage/fs.ts';
nextEnv.loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
const base = path.resolve('outputs/kpl-fresh-prompt-ab-20261002');
process.env.STYLE_LIBRARY_DIR = path.join(base, 'isolated-library');
const data = await readJsonFile(path.join(base, 'B-result.json'));
if (data.comments.length >= 100) process.exit(0);
await writeJsonFile(path.join(base, 'B-first-response.json'), data);
const prompt = await readJsonFile(path.join(base, 'B-prompt.json'));
const messages = [...prompt.messages, { role: 'assistant', content: JSON.stringify(data.comments) }, { role: 'user', content: '刚才返回99条，请再补1条。只输出包含1个字符串的JSON数组。' }];
await writeJsonFile(path.join(base, 'B-supplement-prompt.json'), { schemaVersion: 1, messages });
const start = Date.now();
const result = await generateCommentBatch(messages, 1, undefined, console.log, 'kpl-fresh-B-supplement');
data.supplementMs = Date.now() - start;
data.firstResponseMs = data.elapsedMs;
data.elapsedMs += data.supplementMs;
data.comments.push(...result.batchParsed);
data.actualCount = data.comments.length;
data.uniqueCount = new Set(data.comments).size;
const samples = (await readJsonFile(path.join(base, 'materials.json'))).research.referenceSamples;
data.exactReferenceReuse = data.comments.filter(c => samples.some(s => s.text.trim() === c.trim())).length;
await writeJsonFile(path.join(base, 'B-result.json'), data);
await writeTextFileAtomic(path.join(base, 'B-极简提示词-100条.md'), '# 极简提示词\n\n模型：' + data.model + '；首轮99条耗时 ' + (data.firstResponseMs / 1000).toFixed(1) + ' 秒；补1条 ' + (data.supplementMs / 1000).toFixed(1) + ' 秒。未经审核、筛选或人工改写。\n\n' + data.comments.map((c, i) => (i + 1) + '. ' + c).join('\n\n'));
console.log(JSON.stringify({ actualCount: data.actualCount, elapsedMs: data.elapsedMs, supplementMs: data.supplementMs }));
