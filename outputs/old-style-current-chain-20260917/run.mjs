import {readFile} from 'node:fs/promises';
import nextEnv from '@next/env';
import {prepareWriteCopyContext,chatCompleteStrict} from '../../src/lib/ai.ts';
import {writeJsonFile,writeTextFileAtomic} from '../../src/lib/storage/fs.ts';
nextEnv.loadEnvConfig(process.cwd());
const dir='outputs/old-style-current-chain-20260917';
const draft=JSON.parse(await readFile('style-library/douyin/最翁说游/drafts/2026-09-17T11-08-03-129Z-8593afa753.json','utf8'));
const oldStyle=await readFile('style-library/douyin/最翁说游/.style-history/5415481d44.md','utf8');
const signal=AbortSignal.timeout(240000);
const prepared=await prepareWriteCopyContext({action:'create',targetType:'account',platform:draft.platform,accountId:draft.accountId,mode:draft.mode,prompt:draft.prompt,sourceText:draft.input,originalSourceInput:draft.originalSourceInput,useWebResearch:false,save:false},{signal});
const currentStyle=prepared.writerContext?.styleText || prepared.draftBase?.writerContext?.styleText;
if(!currentStyle)throw Error('缺少风格快照');
let replaced=0;
const messages=prepared.messages.map(m=>{if(m.content.includes(currentStyle)){replaced++;return {...m,content:m.content.replace(currentStyle,oldStyle)};}return m;});
if(replaced!==1)throw Error('风格替换数量异常');
await writeJsonFile(dir+'/request.json',{sourceDraftId:draft.id,styleFile:'5415481d44.md',messages});
console.log('已准备：当前写作链路＋旧卡＋最近水浒卡素材。');
const result=await chatCompleteStrict(messages,undefined,{policy:'writer_generate',signal});
if(!result.ok||result.fallback||!result.text.trim())throw Error(result.userMessage||result.fallbackReason||'生成失败');
await writeJsonFile(dir+'/result.json',result);
await writeTextFileAtomic(dir+'/draft.md',result.text.trim()+'\n');
console.log(JSON.stringify({model:result.model,text:result.text}));
