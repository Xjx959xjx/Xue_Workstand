import path from 'node:path';
import nextEnv from '@next/env';
import { generateCommentBatch } from '../../src/lib/engagement.ts';
import { groupCommentVoiceReferences } from '../../src/lib/engagement-research.ts';
import { commentPipelineCheckpointSchema } from '../../src/lib/storage/schemas.ts';
import { readAiSettings } from '../../src/lib/storage/ai-settings.ts';
import { readJsonFile, writeJsonFile, writeTextFileAtomic } from '../../src/lib/storage/fs.ts';

nextEnv.loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
const originalLibrary = path.resolve(process.env.STYLE_LIBRARY_DIR || 'style-library');
const base = path.resolve('outputs/kpl-simple-prompt-100-20261002');
const settings = await readAiSettings();
const input = (await readJsonFile('outputs/comment-review-ab-20261002/inputs.json')).cases.find((row) => row.id === 'kpl');
if (!input) throw new Error('缺少已保存的 KPL 材料');
const checkpoint = commentPipelineCheckpointSchema.parse(await readJsonFile(path.join(originalLibrary, 'engagement/.cache/pipeline/f9a3712d21.json')));
const samples = checkpoint.research.capturedSamples;
if (!samples?.length) throw new Error('缺少已抓取原评');
process.env.STYLE_LIBRARY_DIR = path.join(base, 'isolated-library');
await writeJsonFile(path.join(process.env.STYLE_LIBRARY_DIR, 'settings/ai-models.json'), settings);
const instruction = '根据正文和抓取的评论给我100条评论，只要符合正文，可重复使用原评。只输出JSON字符串数组。';
const prompt = instruction + '\n\n标题：\n' + input.source.title + '\n\n正文：\n' + input.source.content + '\n\n抓取的评论：\n' + JSON.stringify(groupCommentVoiceReferences(samples));
await writeTextFileAtomic(path.join(base, '实际提示词.txt'), prompt);
await writeJsonFile(path.join(base, 'input.json'), { schemaVersion: 1, title: input.source.title, content: input.source.content, capturedCount: samples.length, samples, instruction, requestedCount: 100 });
const started = Date.now();
console.log('使用已保存 KPL 正文和 ' + samples.length + ' 条已抓取原评，开始生成100条。');
const result = await generateCommentBatch([{ role: 'user', content: prompt }], 100, undefined, console.log, 'kpl-simple-100-20261002');
const comments = result.batchParsed;
const elapsedMs = Date.now() - started;
await writeJsonFile(path.join(base, 'result.json'), { schemaVersion: 1, requestedCount: 100, actualCount: comments.length, elapsedMs, model: result.result.model, attempts: result.attempts, aiReview: false, localFilter: false, comments });
await writeTextFileAtomic(path.join(base, 'KPL-极简提示词-100条评论.md'), '# KPL｜极简提示词生成结果\n\n提示词：' + instruction + '\n\n使用已保存的正文和 ' + samples.length + ' 条原评；实际生成 ' + comments.length + ' 条；模型 ' + result.result.model + '；生成耗时 ' + (elapsedMs / 1000).toFixed(1) + ' 秒。未审核、未筛选、未人工改写。\n\n' + comments.map((text, index) => (index + 1) + '. ' + text).join('\n\n') + '\n');
await writeTextFileAtomic(path.join(base, 'KPL-极简提示词-100条评论.txt'), comments.map((text, index) => (index + 1) + '. ' + text).join('\n') + '\n');
console.log(JSON.stringify({ actualCount: comments.length, elapsedMs, model: result.result.model }));
if (comments.length !== 100) throw new Error('返回条数不足100，现有结果已保存。');
